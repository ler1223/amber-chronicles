"""Адаптивная раскладка: логический холст — это окно, а не фиксированные 1280×800.

Высота холста всегда 800 «единиц интерфейса» (текст и панели сохраняют читаемый размер), а ширина
считается из пропорций окна: 16:10 → 1280, 16:9 → 1422, 21:9 → 1911. На узком окне (уже 16:10)
остаётся 1280×800 с полями. Сцены рисуют в этих координатах, поэтому на ультрашироком экране
интерфейс расходится по ширине, а не стоит колонной 1280 по центру.
"""

BASE_W, BASE_H = 1280, 800
MAX_W = 3200                       # 32:9 и шире: дальше холст не растягиваем, по краям будут поля


def logical_size(win_w, win_h):
    """Размер логического холста под окно: (ширина, высота)."""
    win_w, win_h = max(1, int(win_w)), max(1, int(win_h))
    if win_w / win_h <= BASE_W / BASE_H:
        return BASE_W, BASE_H
    return min(MAX_W, max(BASE_W, int(round(BASE_H * win_w / win_h)))), BASE_H


def content_ox(screen_w):
    """Левый край центральной колонки 1280 на широком холсте."""
    return max(0, (int(screen_w) - BASE_W) // 2)


def battle_rects(screen_w, grid_w=880, panel_w=340, margin=16):
    """Поле боя и правая панель: доска по центру свободной части, панель прижата к правому краю."""
    right = int(screen_w) - panel_w - margin
    grid_x = max(24, (right - grid_w) // 2)
    return grid_x, right
